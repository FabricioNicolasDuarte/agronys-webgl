export const LANGS = [
  { id: "es", label: "ES", title: "Espa\u00f1ol", html: "es" },
  { id: "en", label: "EN", title: "English", html: "en" },
  { id: "pt", label: "PT", title: "Portugu\u00eas", html: "pt" },
  { id: "zh", label: "\u4e2d", title: "\u4e2d\u6587", html: "zh-CN" },
];

const LANG_IDS = new Set(LANGS.map((l) => l.id));

export function langSwitchMarkup() {
  return LANGS.map(
    (l) =>
      `<button type="button" data-lang="${l.id}" title="${l.title}" aria-label="${l.title}">${l.label}</button>`
  ).join("");
}

export function getLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (LANG_IDS.has(saved)) return saved;
  } catch {
    /* ignore */
  }
  return "es";
}

export function setLang(lang) {
  const next = LANG_IDS.has(lang) ? lang : "es";
  try {
    localStorage.setItem(KEY, next);
  } catch {
    /* ignore */
  }
  const meta = LANGS.find((l) => l.id === next);
  document.documentElement.lang = meta ? meta.html : "es";
  return next;
}

export function t() {
  return STR[getLang()] ?? STR.es;
}

export function applyChromeI18n() {
  const copy = t();
  const meta = LANGS.find((l) => l.id === getLang());
  document.documentElement.lang = meta ? meta.html : "es";
  document.querySelectorAll(".lang-switch").forEach((box) => {
    if (box.querySelectorAll("[data-lang]").length !== LANGS.length) {
      box.innerHTML = langSwitchMarkup();
    }
  });
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const value = copy[key];
    if (typeof value !== "string") return;
    const asHtml = el.dataset.i18nHtml === "1";
    if (asHtml) el.innerHTML = value;
    else el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria;
    if (copy[key]) el.setAttribute("aria-label", copy[key]);
  });
  const cards = copy.cards;
  if (cards) {
    Object.entries(cards).forEach(([id, texts]) => {
      const panel = document.querySelector(`.panel[data-layer="${id}"]`);
      if (panel) {
        const h = panel.querySelector("h2");
        const k = panel.querySelector(".panel-kicker");
        const n = panel.querySelector(".note");
        if (h) h.textContent = texts.title;
        if (k) k.textContent = texts.kicker;
        if (n && texts.note) n.textContent = texts.note;
      }
      const btn = document.querySelector(`.svc-btn[data-layer="${id}"]`);
      if (btn) {
        btn.setAttribute("aria-label", texts.title);
        btn.setAttribute("data-tip", texts.title);
      }
    });
  }
  document.querySelectorAll(".lang-switch [data-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.lang === getLang() ? "true" : "false");
  });
  const page = document.body.dataset.page || "index";
  if (copy.titles?.[page]) document.title = copy.titles[page];
  const desc = document.querySelector('meta[name="description"]');
  if (desc && copy.descs?.[page]) desc.setAttribute("content", copy.descs[page]);
}

export function bindLangSwitch() {
  document.querySelectorAll(".lang-switch").forEach((box) => {
    box.innerHTML = langSwitchMarkup();
  });
  applyChromeI18n();
  if (document.documentElement.dataset.langBound === "1") return;
  document.documentElement.dataset.langBound = "1";
  document.addEventListener("click", (e) => {
    const btn = e.target.closest(".lang-switch [data-lang]");
    if (!btn) return;
    setLang(btn.dataset.lang);
    applyChromeI18n();
    window.dispatchEvent(new CustomEvent("agronys:lang"));
  });
}
